-- ============================================================================
--  008-feedback-sampling.sql
--  ถามความเห็นเป็นครั้งคราว แทนที่จะถามทุกคำตอบ
-- ----------------------------------------------------------------------------
--  ปัญหาของการถามทุกครั้ง
--
--    ปุ่มให้คะแนนขึ้นใต้คำตอบทุกข้อ ซึ่งมีผลเสียสองอย่าง
--      ผู้ใช้รำคาญ  ถูกถามซ้ำ ๆ จนเลิกสนใจ แล้วก็เลิกกดไปเลย
--      ข้อมูลเอียง  คนที่ยังกดอยู่คือคนกลุ่มเล็กที่ขยันกดเป็นพิเศษ
--                  ซึ่งไม่ได้แทนผู้ใช้ทั้งหมด
--
--    การถามน้อยลงแต่ได้คำตอบจากคนหลากหลายกว่า มีค่ามากกว่าการถามถี่
--
--  วิธีที่เลือก นับจำนวนคำตอบแล้วถามเมื่อครบรอบ โดยรอบเป็นค่าสุ่ม 10 ถึง 30
--
--    ทำไมไม่ใช้การสุ่มล้วน เช่น มีโอกาสขึ้น 5 เปอร์เซ็นต์ทุกครั้ง
--      การสุ่มล้วนทำให้เกิดกรณีที่ขึ้นสองครั้งติดกัน ซึ่งน่ารำคาญกว่าเดิม
--      และกรณีที่ไม่ขึ้นเลยเป็นร้อยข้อ ซึ่งทำให้ไม่ได้ข้อมูล
--      การนับรอบรับประกันระยะห่างขั้นต่ำ และรับประกันว่าจะได้ถามแน่นอน
--
--    ทำไมรอบต้องสุ่ม ไม่ใช้เลขคงที่เช่นทุก 20 ข้อ
--      ถ้าคงที่ ผู้ใช้ประจำจะจับจังหวะได้ว่าอีกกี่ข้อปุ่มจะขึ้น
--      และถ้าผู้ใช้หลายคนเริ่มพร้อมกัน จะถูกถามพร้อมกันเป็นล็อต
--      การสุ่มช่วงทำให้การเก็บข้อมูลกระจายตัวตามธรรมชาติมากกว่า
--
--    ทำไมนับแยกรายคน ไม่นับรวมทั้งระบบ
--      ถ้านับรวม คนที่ถามข้อเดียวอาจโดนถามทุกครั้ง
--      ส่วนคนที่ถามเยอะอาจไม่โดนถามเลย ซึ่งไม่ยุติธรรมและได้ข้อมูลเอียง
--
--  คำถามแรกของผู้ใช้ใหม่ จะถูกถามเสมอ
--    ตั้งใจให้เป็นแบบนี้ เพราะถ้าไม่เคยเห็นปุ่มเลยในสิบข้อแรก
--    ผู้ใช้จะไม่รู้ว่าระบบมีช่องทางให้บอกว่าคำตอบตรงหรือไม่ตรง
--    เห็นครั้งแรกครั้งเดียวก็พอให้รู้ว่ามีอยู่ แล้วหลังจากนั้นค่อยเว้นระยะ
--
--  เรื่องความเป็นส่วนตัว
--    ตัวนับอยู่ในตาราง users ซึ่งมีอยู่แล้ว ไม่ได้เพิ่มการเก็บข้อความใด ๆ
--    และตาราง answer_feedback ยังไม่มีคอลัมน์ที่ระบุตัวผู้ใช้เหมือนเดิม
--    จึงยังบอกไม่ได้อยู่ดีว่าคะแนนแต่ละอันมาจากใคร
--
--  วิธีรัน
--    docker cp postgres\migrations\008-feedback-sampling.sql tax-advisor-postgres:/tmp/m008.sql
--    docker exec -it tax-advisor-postgres psql -U n8n_admin -d tax_advisor -f /tmp/m008.sql
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
--  ตัวนับและรอบของแต่ละคน
-- ---------------------------------------------------------------------------
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS msgs_since_feedback INTEGER NOT NULL DEFAULT 0;

-- รอบของแต่ละคนไม่เท่ากัน สุ่มตั้งแต่ตอนสร้างแถว
-- floor(random() * 21) ให้เลข 0 ถึง 20 บวก 10 จึงได้ 10 ถึง 30
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS feedback_after INTEGER NOT NULL
    DEFAULT (10 + floor(random() * 21)::int);

COMMENT ON COLUMN users.msgs_since_feedback IS
  'จำนวนคำตอบที่ผ่านไปนับจากครั้งล่าสุดที่ถามความเห็น';
COMMENT ON COLUMN users.feedback_after IS
  'ครบกี่คำตอบจึงจะถามความเห็นอีกครั้ง สุ่มใหม่ทุกครั้งที่ถาม ช่วง 10 ถึง 30';

-- ---------------------------------------------------------------------------
--  ผู้ใช้เดิมที่มีอยู่แล้ว
-- ---------------------------------------------------------------------------
--  ตั้งตัวนับให้เท่ากับรอบพอดี เพื่อให้ถูกถามในคำตอบถัดไปหนึ่งครั้ง
--  แล้วหลังจากนั้นจึงเข้าสู่จังหวะปกติ
--  ถ้าตั้งเป็นศูนย์ ผู้ใช้เดิมจะไม่เห็นปุ่มเลยจนกว่าจะถามครบอีกสิบถึงสามสิบข้อ
-- ---------------------------------------------------------------------------
UPDATE users SET msgs_since_feedback = feedback_after;

COMMIT;


-- ============================================================================
--  ตรวจผลหลังรัน
-- ============================================================================

SELECT id, display_name, msgs_since_feedback, feedback_after,
       (msgs_since_feedback >= feedback_after) AS จะถูกถามในข้อถัดไป
FROM users
ORDER BY id;


-- ============================================================================
--  วิธีบังคับให้ปุ่มขึ้นทันที ใช้ตอนสาธิตให้อาจารย์ดู
-- ----------------------------------------------------------------------------
--  ปกติปุ่มจะขึ้นทุก 10 ถึง 30 คำตอบ ซึ่งสาธิตสดไม่ทัน
--  คำสั่งนี้ตั้งตัวนับให้ครบรอบพอดี ปุ่มจะขึ้นในคำตอบถัดไปทันที
