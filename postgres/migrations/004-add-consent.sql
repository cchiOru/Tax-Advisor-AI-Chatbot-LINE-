--  เหตุผล
--    ระบบเก็บชื่อบัญชี LINE ข้อความที่ผู้ใช้พิมพ์ และคำตอบของระบบ
--    ซึ่งเป็นข้อมูลส่วนบุคคลตามพระราชบัญญัติคุ้มครองข้อมูลส่วนบุคคล พ.ศ. 2562
--    การเก็บจึงต้องได้รับความยินยอมจากเจ้าของข้อมูลก่อน
--
--    เดิมระบบเก็บทุกอย่างทันทีที่ผู้ใช้ทัก โดยไม่เคยถามและไม่เคยบันทึกว่าถามแล้วหรือยัง
--
--  หลักการที่ใช้ออกแบบ
--    1. ความยินยอมต้องให้โดยอิสระ ปฏิเสธแล้วต้องยังใช้งานได้ตามปกติ
--       ระบบจึงยังตอบคำถามให้ครบทุกอย่าง เพียงแต่ไม่เก็บข้อความ
--    2. ถอนความยินยอมได้ตลอดเวลา ผู้ใช้พิมพ์ว่า ลบข้อมูลของฉัน แล้วระบบลบให้ทันที
--    3. บันทึกเวลาที่ให้ความยินยอมไว้ เพื่อพิสูจน์ได้ว่าขอเมื่อใดและได้รับเมื่อใด
--    4. บันทึกรุ่นของข้อความที่ใช้ขอ เพราะถ้าแก้ข้อความในอนาคต
--       ต้องรู้ว่าผู้ใช้แต่ละคนยินยอมกับเงื่อนไขฉบับใด และอาจต้องขอใหม่
--
--  ค่า consent_status ที่เป็นไปได้
--    pending   ถามแล้วแต่ยังไม่ตอบ  ระบบจะยังไม่เก็บข้อความจนกว่าจะกดยินยอม
--    granted   ยินยอม              เก็บข้อความและใช้ความจำบทสนทนาได้
--    denied    ไม่ยินยอม            ตอบคำถามได้ตามปกติ แต่ไม่เก็บข้อความและไม่มีความจำ
--
--  วิธีรัน
--    docker cp postgres\migrations\004-add-consent.sql tax-advisor-postgres:/tmp/m004.sql
--    docker exec -it tax-advisor-postgres psql -U n8n_admin -d tax_advisor -f /tmp/m004.sql
