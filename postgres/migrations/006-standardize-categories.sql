--  006-standardize-categories.sql
--  จัดหมวดฐานข้อมูลกฎหมายให้ตรงกับโครงสร้างประมวลรัษฎากร
--  และเพิ่มคอลัมน์บอกว่าตัวเลขในรายการนั้นต้องเอาไปคำนวณต่อหรือไม่
-- ----------------------------------------------------------------------------
--  เหตุผลที่ต้องทำ
--
--    หมวดเดิม 26 หมวดถูกตั้งขึ้นเองระหว่างพัฒนา ไม่ได้อิงโครงสร้างกฎหมายใด ๆ
--    ผลคือมีปัญหาสามอย่างที่ตรวจพบเมื่อ 10 สิงหาคม 2569
--
--      ซ้ำซ้อน      คำนวณภาษี กับ การคำนวณภาษี เป็นเรื่องเดียวกันแต่แยกกันอยู่
--                  ค่าลดหย่อนภาษี กับ สิทธิ์ลดหย่อน ก็เช่นกัน
--      กระจัดกระจาย 7 หมวดจาก 26 มีรายการเดียว ซึ่งไม่ได้ช่วยจัดกลุ่มอะไรเลย
--      นอกขอบเขต   ภาษีป้าย อากรแสตมป์ อยู่ในระบบที่ทำเฉพาะภาษีเงินได้บุคคลธรรมดา
--
--    หมวดใหม่ยึดตามลำดับของประมวลรัษฎากร หมวด 3 ส่วน 2
--    ซึ่งเป็นลำดับเดียวกับที่เว็บไซต์กรมสรรพากรใช้อธิบายภาษีเงินได้บุคคลธรรมดา
--    ทุกหมวดจึงอ้างมาตรารองรับได้ ต่างจากหมวดเดิมที่ตอบไม่ได้ว่าแบ่งตามอะไร
--
--  ผลกระทบที่วัดแล้วก่อนทำ
--    ทดลองย้ายหมวดแล้วรันการค้นข้อมูลกับคำถามทดสอบ 115 ข้อ
--    จำนวนคำถามที่บริบทไม่มีคำตอบ เท่าเดิมคือศูนย์ ทั้งก่อนและหลังย้าย
--    แปลว่าการย้ายหมวดไม่ทำให้ระบบค้นข้อมูลแย่ลง
--
--    แต่ชื่อหมวดถูกส่งเข้าไปในข้อมูลที่ให้ AI อ่านด้วย
--    ถ้อยคำของคำตอบจึงอาจเปลี่ยนได้ ต้องวัดผลใหม่หนึ่งรอบหลังทำ
--
--  ย้อนกลับได้
--    หมวดเดิมถูกเก็บไว้ในคอลัมน์ category_legacy
--    ถ้าผลวัดแย่ลง ย้อนได้ด้วยคำสั่งเดียวที่อยู่ท้ายไฟล์นี้
--
--  วิธีรัน
--    docker cp postgres\migrations\006-standardize-categories.sql tax-advisor-postgres:/tmp/m006.sql
--    docker exec -it tax-advisor-postgres psql -U n8n_admin -d tax_advisor -f /tmp/m006.sql
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
--  1) เก็บหมวดเดิมไว้ก่อน เพื่อให้ย้อนกลับได้
-- ---------------------------------------------------------------------------
ALTER TABLE tax_law_knowledge
    ADD COLUMN IF NOT EXISTS category_legacy VARCHAR(100);

-- คัดลอกเฉพาะครั้งแรกที่รัน ถ้ารันซ้ำจะไม่ทับของเดิมที่เก็บไว้
UPDATE tax_law_knowledge
SET category_legacy = category
WHERE category_legacy IS NULL;

COMMENT ON COLUMN tax_law_knowledge.category_legacy IS
  'หมวดเดิมก่อนจัดใหม่ตามประมวลรัษฎากร เก็บไว้เพื่อย้อนกลับได้ถ้าผลวัดแย่ลง';


-- ---------------------------------------------------------------------------
--  2) คอลัมน์ใหม่ ตัวเลขในรายการนี้ต้องเอาไปคำนวณต่อหรือไม่
-- ---------------------------------------------------------------------------
--  ใช้ทำอะไร
--    ความเสี่ยงที่เกิดซ้ำในระบบนี้คือแบบจำลองเห็นตัวเลขในเนื้อหา
--    แล้วเอาไปบวกลบเองแทนที่จะเรียกเครื่องคำนวณ ซึ่งได้คำตอบที่ผิดแบบดูน่าเชื่อ
--
--    คอลัมน์นี้บอกว่าตัวเลขในรายการเป็นค่าตั้งต้นที่ต้องคำนวณต่อ
--    ระบบจะได้แนบคำสั่งเตือนเพิ่มได้ว่าห้ามคิดเลขเอง
--
--  สิ่งที่คอลัมน์นี้ไม่ได้ทำ
--    ไม่ได้ใช้ตัดสินว่าคำถามของผู้ใช้ต้องเรียกเครื่องคำนวณหรือไม่
--    เรื่องนั้นตัดสินจากคำถามเหมือนเดิม เพราะรายการความรู้เดียวกัน
--    ตอบได้ทั้งคำถามที่อยากรู้กฎ และคำถามที่อยากได้ตัวเลข
--    เช่น ลดหย่อนบุตรได้เท่าไหร่ กับ เงินเดือน 50,000 มีบุตร 2 คน เสียเท่าไหร่
--    ค้นเจอรายการเดียวกัน แต่ต้องการคำตอบคนละแบบ
-- ---------------------------------------------------------------------------
ALTER TABLE tax_law_knowledge
    ADD COLUMN IF NOT EXISTS needs_calculation BOOLEAN;

ALTER TABLE tax_law_knowledge
    ADD COLUMN IF NOT EXISTS calc_verified BOOLEAN NOT NULL DEFAULT false;

COMMENT ON COLUMN tax_law_knowledge.needs_calculation IS
  'true คือตัวเลขในรายการนี้เป็นเพดานหรืออัตราที่ต้องเอาไปคำนวณกับรายได้ของผู้ใช้';
COMMENT ON COLUMN tax_law_knowledge.calc_verified IS
  'true คือผู้ดูแลตรวจยืนยันค่า needs_calculation แล้ว false คือยังเป็นค่าที่ระบบเดาให้';


-- ---------------------------------------------------------------------------
--  3) ย้ายหมวดเดิมเข้าหมวดใหม่
-- ---------------------------------------------------------------------------
--  หมวดใหม่และมาตราที่รองรับ
--    ผู้มีหน้าที่เสียภาษี          ม.56
--    ประเภทเงินได้พึงประเมิน      ม.40(1) ถึง (8)
--    เงินได้ที่ได้รับยกเว้น        ม.42
--    การหักค่าใช้จ่าย             ม.42 ทวิ ถึง ม.46
--    การหักลดหย่อน               ม.47
--    การคำนวณภาษี                ม.48
--    การยื่นแบบและชำระภาษี        ม.56 ม.57
--    การขอคืนภาษี                ม.63
--    เบี้ยปรับ เงินเพิ่ม และโทษ    ม.22 ม.27 ม.35
--    การอุทธรณ์                  ม.30
--    ภาษีอื่นที่เกี่ยวข้อง          นอกขอบเขตภาษีเงินได้บุคคลธรรมดา แต่ผู้ใช้ถามถึง
-- ---------------------------------------------------------------------------
UPDATE tax_law_knowledge SET category = CASE category_legacy
    WHEN 'ค่าลดหย่อนภาษี'          THEN 'การหักลดหย่อน'
    WHEN 'สิทธิ์ลดหย่อน'            THEN 'การหักลดหย่อน'
    WHEN 'เคล็ดลับประหยัดภาษี'      THEN 'การหักลดหย่อน'

    WHEN 'คำนวณภาษี'              THEN 'การคำนวณภาษี'
    WHEN 'การคำนวณภาษี'            THEN 'การคำนวณภาษี'
    -- เงินก้อนตอนออกจากงานเป็นเรื่องวิธีคำนวณแยกตามมาตรา 48(5) จึงอยู่หมวดคำนวณ
    WHEN 'ออกจากงานและเกษียณ'      THEN 'การคำนวณภาษี'

    WHEN 'ประเภทเงินได้'           THEN 'ประเภทเงินได้พึงประเมิน'
    WHEN 'เงินได้เฉพาะกรณี'         THEN 'ประเภทเงินได้พึงประเมิน'

    WHEN 'เงินได้ยกเว้นภาษี'         THEN 'เงินได้ที่ได้รับยกเว้น'

    WHEN 'กำหนดการยื่นภาษี'         THEN 'การยื่นแบบและชำระภาษี'
    WHEN 'แบบแสดงรายการภาษี'       THEN 'การยื่นแบบและชำระภาษี'
    WHEN 'ขั้นตอนปฏิบัติ'            THEN 'การยื่นแบบและชำระภาษี'
    WHEN 'ภาษีหัก ณ ที่จ่าย'         THEN 'การยื่นแบบและชำระภาษี'

    WHEN 'การคืนภาษี'              THEN 'การขอคืนภาษี'
    WHEN 'โทษและเบี้ยปรับ'          THEN 'เบี้ยปรับ เงินเพิ่ม และโทษ'
    WHEN 'แก้ไขและโต้แย้ง'          THEN 'การอุทธรณ์'

    WHEN 'ภาษีเงินได้บุคคลธรรมดา'    THEN 'ผู้มีหน้าที่เสียภาษี'
    WHEN 'สถานการณ์เฉพาะบุคคล'      THEN 'ผู้มีหน้าที่เสียภาษี'

    -- ที่เหลือคือภาษีประเภทอื่นที่อยู่นอกขอบเขตของระบบ แต่ยังเก็บไว้ตอบได้
    ELSE 'ภาษีอื่นที่เกี่ยวข้อง'
END;


-- ---------------------------------------------------------------------------
--  4) เดาค่าตั้งต้นของ needs_calculation จากเนื้อหา
-- ---------------------------------------------------------------------------
--  ทำไมต้องเดา ไม่ตั้งเป็นค่าเดียวทั้งหมด
--    ถ้าตั้งเป็น true หมด ระบบจะเตือนทุกรายการจนสัญญาณเจือจางไม่มีความหมาย
--    ถ้าตั้งเป็น false หมด ก็ไม่ได้ประโยชน์อะไรจนกว่าจะมีคนไล่ติ๊กครบ 97 รายการ
--
--    การเดาแล้วให้ผู้ดูแลไล่ยืนยันทีหลัง ได้ประโยชน์ทันทีและแก้ได้เมื่อเจอที่ผิด
--    คอลัมน์ calc_verified บอกว่ารายการไหนยังเป็นค่าที่เดาไว้
--
--  เกณฑ์การเดา
--    เป็น true เมื่ออยู่ในหมวดที่เกี่ยวกับการคิดเงิน และในเนื้อหามีจำนวนเงิน
--    รูปแบบจำนวนเงินที่ใช้ตรวจคือตัวเลขที่มีเครื่องหมายคั่นหลักพันตามด้วยคำว่าบาท
--    หรือมีเครื่องหมายร้อยละ ซึ่งเป็นรูปแบบที่ใช้เขียนเพดานและอัตราในฐานข้อมูลนี้
-- ---------------------------------------------------------------------------
UPDATE tax_law_knowledge
SET needs_calculation = (
    category IN ('การหักลดหย่อน', 'การคำนวณภาษี', 'การหักค่าใช้จ่าย',
                 'ประเภทเงินได้พึงประเมิน', 'เบี้ยปรับ เงินเพิ่ม และโทษ')
    AND (content ~ '[0-9],[0-9]{3}\s*บาท' OR content ~ 'ร้อยละ\s*[0-9]' OR content ~ '[0-9]+%')
)
WHERE needs_calculation IS NULL;

-- รายการที่เหลือซึ่งยังเป็น NULL คือไม่เข้าเกณฑ์ ให้ถือว่าไม่ต้องคำนวณต่อ
UPDATE tax_law_knowledge SET needs_calculation = false WHERE needs_calculation IS NULL;

ALTER TABLE tax_law_knowledge ALTER COLUMN needs_calculation SET NOT NULL;
ALTER TABLE tax_law_knowledge ALTER COLUMN needs_calculation SET DEFAULT false;


-- ---------------------------------------------------------------------------
--  5) ดัชนีสำหรับหน้าหลังบ้าน
-- ---------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_tax_law_knowledge_category
    ON tax_law_knowledge (category);
CREATE INDEX IF NOT EXISTS idx_tax_law_knowledge_unverified
    ON tax_law_knowledge (calc_verified) WHERE calc_verified = false;

-- ให้บัญชีของหน้าหลังบ้านแก้คอลัมน์ใหม่ได้
GRANT SELECT, INSERT, UPDATE, DELETE ON tax_law_knowledge TO tax_admin_readonly;

COMMIT;


-- ============================================================================
--  ตรวจผลหลังรัน
-- ============================================================================

SELECT category AS หมวดใหม่,
       count(*) AS จำนวน,
       count(*) FILTER (WHERE needs_calculation) AS ต้องคำนวณต่อ,
       count(*) FILTER (WHERE NOT calc_verified) AS ยังไม่ได้ตรวจ
FROM tax_law_knowledge
GROUP BY 1
ORDER BY 2 DESC;

-- ต้องได้ 0 แถว ถ้ามีแปลว่ามีรายการที่ย้ายหมวดไม่สำเร็จ
SELECT id, category, category_legacy
FROM tax_law_knowledge
WHERE category NOT IN (
  'ผู้มีหน้าที่เสียภาษี', 'ประเภทเงินได้พึงประเมิน', 'เงินได้ที่ได้รับยกเว้น',
  'การหักค่าใช้จ่าย', 'การหักลดหย่อน', 'การคำนวณภาษี',
  'การยื่นแบบและชำระภาษี', 'การขอคืนภาษี', 'เบี้ยปรับ เงินเพิ่ม และโทษ',
  'การอุทธรณ์', 'ภาษีอื่นที่เกี่ยวข้อง'
);


