--  009-verify-calc-flags.sql
--  แก้ค่าที่ระบบเดาผิด และยืนยันรายการที่ไล่อ่านแล้ว
-- ----------------------------------------------------------------------------
--  ที่มา
--
--    migration 006 เดาค่าคอลัมน์ needs_calculation ให้ทุกรายการ
--    ด้วยเกณฑ์สองชั้น คือต้องอยู่ในห้าหมวดที่เกี่ยวกับเงิน และเนื้อหาต้องมีจำนวนเงิน
--
--    ปัญหาคือชั้นแรกตัดสินจากหมวดก่อน ถ้ารายการไม่ได้อยู่ในห้าหมวดนั้น
--    จะถูกเดาว่าไม่ต้องคำนวณทันที ไม่ว่าเนื้อหาจะมีตัวเลขมากแค่ไหน
--
--    ไล่ตรวจแล้วพบ 20 รายการที่เข้าข่ายนี้ คือถูกเดาว่าตอบได้เลย
--    ทั้งที่เนื้อหามีจำนวนเงินหรืออัตราอยู่ ในจำนวนนี้ 8 รายการเดาผิดจริง
--
--    รายการที่ผิดหนักที่สุดคือตารางอัตราภาษีก้าวหน้า
--    ซึ่งอยู่ในหมวดผู้มีหน้าที่เสียภาษี จึงหลุดเกณฑ์ไป
--    ทั้งที่เป็นตัวเลขชุดที่ถูกเอาไปคิดกับเงินได้ของผู้ใช้ทุกครั้งที่มีการคำนวณ
--
--  เกณฑ์ที่ใช้ตัดสินในไฟล์นี้
--    ใช่  ตัวเลขในรายการนี้ต้องเอาไปคิดกับตัวเลขของผู้ใช้
--         ไม่ว่าจะเป็นการหักลบ คูณอัตรา หรือเทียบว่าถึงเกณฑ์หรือยัง
--    ไม่   ตอบตามที่เขียนไว้ได้ทันที เช่นกำหนดวัน ขั้นตอน หรือชื่อแบบฟอร์ม
--
--  ข้อจำกัดของไฟล์นี้ที่ต้องรู้
--    ไฟล์นี้ยืนยันเฉพาะ 20 รายการที่ไล่อ่านจริง
--    อีก 78 รายการยังเป็นค่าที่ระบบเดาไว้และยังไม่มีใครตรวจ
--    ซึ่งดูได้จากตัวกรองในหน้าจัดการฐานข้อมูล
--
--  วิธีรัน
--    docker cp postgres\migrations\009-verify-calc-flags.sql tax-advisor-postgres:/tmp/m009.sql
--    docker exec -it tax-advisor-postgres psql -U n8n_admin -d tax_advisor -f /tmp/m009.sql
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
--  1) แปดรายการที่เดาผิด ต้องเป็นใช่ ต้องคำนวณต่อ
-- ---------------------------------------------------------------------------
--  เหตุผลรายรายการ
--
--    ฐานภาษีและอัตราภาษีเงินได้บุคคลธรรมดา ปี 2567
--      ตารางอัตราก้าวหน้าทั้งตาราง ตั้งแต่ยกเว้น 150,000 บาทแรกจนถึงขั้นสูงสุด
--      เป็นตัวเลขที่ต้องเอาไปคูณกับเงินได้สุทธิของผู้ใช้ทุกครั้ง
--
--    อัตราภาษีหัก ณ ที่จ่ายที่พบบ่อยสำหรับบุคคลธรรมดา
--      อัตราร้อยละ 3 และ 5 ต้องเอาไปคูณกับยอดเงินที่ผู้ใช้ได้รับ
--
--    เกณฑ์เงินได้ที่ทำให้ต้องยื่นแบบแสดงรายการ
--      120,000 บาทสำหรับคนโสด และ 220,000 บาทสำหรับคู่สมรส
--      ต้องเอาไปเทียบกับเงินได้ทั้งปีของผู้ใช้ว่าถึงเกณฑ์หรือยัง
--
--    นักเรียนนักศึกษาและผู้มีรายได้น้อย
--      เกณฑ์ 120,000 และ 60,000 บาทสำหรับการยื่น
--      และ 30,000 บาทที่ทำให้ผู้ปกครองใช้สิทธิลดหย่อนบุตรไม่ได้
--
--    ผู้มีเงินได้ถึงแก่ความตายและกองมรดก
--      ค่าลดหย่อนส่วนตัว 60,000 บาทที่ยังได้เต็มจำนวน ต้องเอาไปหักจริง
--
--    การยื่นภาษีของสามีภริยา ยื่นรวมหรือแยก
--      ค่าลดหย่อนส่วนตัวและคู่สมรสฝ่ายละ 60,000 บาท
--      และการเลือกวิธียื่นทำให้ภาษีที่คำนวณได้ต่างกัน
--
--    เงินได้ที่ได้รับยกเว้นไม่ต้องนำมารวมคำนวณภาษี
--      ดอกเบี้ยเงินฝากออมทรัพย์รวมทั้งปีไม่เกิน 20,000 บาท
--      ต้องเอาไปเทียบกับดอกเบี้ยที่ผู้ใช้ได้รับจริง
--
--    การผ่อนชำระภาษีและช่องทางการชำระเงิน
--      เกณฑ์ 3,000 บาท ต้องเอาไปเทียบกับภาษีที่ผู้ใช้คำนวณได้
-- ---------------------------------------------------------------------------
UPDATE tax_law_knowledge
SET needs_calculation = true,
    calc_verified     = true
WHERE title IN (
  'ฐานภาษีและอัตราภาษีเงินได้บุคคลธรรมดา ปี 2567',
  'อัตราภาษีหัก ณ ที่จ่ายที่พบบ่อยสำหรับบุคคลธรรมดา',
  'เกณฑ์เงินได้ที่ทำให้ต้องยื่นแบบแสดงรายการ',
  'นักเรียนนักศึกษาและผู้มีรายได้น้อย',
  'ผู้มีเงินได้ถึงแก่ความตายและกองมรดก',
  'การยื่นภาษีของสามีภริยา ยื่นรวมหรือแยก',
  'เงินได้ที่ได้รับยกเว้นไม่ต้องนำมารวมคำนวณภาษี',
  'การผ่อนชำระภาษีและช่องทางการชำระเงิน'
);


-- ---------------------------------------------------------------------------
--  2) สิบสองรายการที่เดาถูกแล้ว ยืนยันว่าตอบได้เลย
-- ---------------------------------------------------------------------------
--  กลุ่มที่หนึ่ง ขั้นตอนและกำหนดเวลา ตัวเลขที่มีเป็นวันที่หรือเลขมาตรา
--    ตัวบทกฎหมายภาษีอยู่ที่ไหน และควรอ้างอิงอย่างไร
--    ขั้นตอนการยื่นภาษีออนไลน์ที่เว็บไซต์กรมสรรพากร
--    กำหนดเวลายื่นแบบภาษีเงินได้บุคคลธรรมดา ปี 2568 (สำหรับเงินได้ปี 2567)
--    แบบ ภ.ง.ด.94 ภาษีครึ่งปี
--      ตัวเลขในรายการนี้คือเลขประเภทเงินได้กับวันที่ ไม่ใช่จำนวนเงิน
--
--  กลุ่มที่สอง การอุทธรณ์และการตรวจสอบ ตัวเลขเป็นกำหนดเวลาและอายุความ
--    ยื่นแบบผิดหรือลืมใส่รายการ ต้องยื่นเพิ่มเติม
--    ยื่นภาษีย้อนหลังและอายุความการประเมิน
--    ถูกกรมสรรพากรเรียกตรวจสอบ ต้องทำอย่างไร
--
--  กลุ่มที่สาม ภาษีประเภทอื่น มีอัตราอยู่จริง แต่ระบบถูกสั่งห้ามคำนวณให้
--    เพราะไม่มีเครื่องมือรองรับ ต้องแนะนำหน่วยงานที่รับผิดชอบแทน
--    ค่าไม่ต้องคำนวณในกลุ่มนี้จึงมีความหมายว่า ตอบตามที่เขียนแล้วส่งต่อ
--    ภาษีมูลค่าเพิ่ม VAT อัตราและเกณฑ์จดทะเบียน
--    ภาษีธุรกิจเฉพาะและการขายอสังหาริมทรัพย์
--    ภาษีเงินได้นิติบุคคลและสิทธิประโยชน์ของ SME
--    ภาษีที่ดินและสิ่งปลูกสร้าง
--    ภาษีการรับมรดกและภาษีการรับให้
--
--  บันทึกความผิดพลาดของไฟล์นี้เอง
--    ตอนเขียนครั้งแรก รายการภาษีที่ดินและสิ่งปลูกสร้างถูกเขียนชื่อผิด
--    เป็น ภาษีอื่นที่เกี่ยวข้อง ซึ่งเป็นชื่อหมวด ไม่ใช่ชื่อเรื่อง
--
--    สาเหตุคือตอนนั้นชื่อเรื่องในไฟล์ seed ถูกทับด้วยชื่อหมวดอยู่
--    จากการแทนข้อความทั้งไฟล์ตอนย้ายหมวด และยังไม่มีใครรู้
--    ผมจึงคัดชื่อผิดมาจากไฟล์ที่เพี้ยนแล้ว
--
--    ผลคือคำสั่งด้านล่างหาไม่เจอหนึ่งรายการ อัปเดตได้ 11 แถวแทนที่จะเป็น 12
--    ซึ่งไม่มีข้อความแจ้งเตือนใด ๆ เพราะ SQL ถือว่าการอัปเดต 0 แถวไม่ใช่ข้อผิดพลาด
--    จับได้จากการนับจำนวนแถวที่ขึ้นบนหน้าจอเทียบกับจำนวนชื่อในรายการ
-- ---------------------------------------------------------------------------
UPDATE tax_law_knowledge
SET needs_calculation = false,
    calc_verified     = true
WHERE title IN (
  'ตัวบทกฎหมายภาษีอยู่ที่ไหน และควรอ้างอิงอย่างไร',
  'ขั้นตอนการยื่นภาษีออนไลน์ที่เว็บไซต์กรมสรรพากร',
  'กำหนดเวลายื่นแบบภาษีเงินได้บุคคลธรรมดา ปี 2568 (สำหรับเงินได้ปี 2567)',
  'แบบ ภ.ง.ด.94 ภาษีครึ่งปี',
  'ยื่นแบบผิดหรือลืมใส่รายการ ต้องยื่นเพิ่มเติม',
  'ยื่นภาษีย้อนหลังและอายุความการประเมิน',
  'ถูกกรมสรรพากรเรียกตรวจสอบ ต้องทำอย่างไร',
  'ภาษีมูลค่าเพิ่ม VAT อัตราและเกณฑ์จดทะเบียน',
  'ภาษีธุรกิจเฉพาะและการขายอสังหาริมทรัพย์',
  'ภาษีเงินได้นิติบุคคลและสิทธิประโยชน์ของ SME',
  'ภาษีที่ดินและสิ่งปลูกสร้าง',
  'ภาษีการรับมรดกและภาษีการรับให้'
);

COMMIT;


-- ============================================================================
--  ตรวจผลหลังรัน
-- ============================================================================

-- ต้องได้ 20 แถว ตรวจแล้วทั้งหมด
SELECT needs_calculation AS ต้องคำนวณต่อ, count(*) AS จำนวน
FROM tax_law_knowledge
WHERE calc_verified
GROUP BY 1 ORDER BY 1 DESC;

-- ภาพรวมทั้งฐานข้อมูล
SELECT category AS หมวด,
       count(*) AS จำนวน,
       count(*) FILTER (WHERE needs_calculation) AS ต้องคำนวณต่อ,
       count(*) FILTER (WHERE NOT calc_verified) AS ยังไม่ได้ตรวจ
FROM tax_law_knowledge
GROUP BY 1 ORDER BY 2 DESC;

-- รายการที่ยังไม่มีใครตรวจ ควรเหลือ 78 รายการ
SELECT count(*) AS ยังไม่ได้ตรวจทั้งหมด
FROM tax_law_knowledge WHERE NOT calc_verified;


