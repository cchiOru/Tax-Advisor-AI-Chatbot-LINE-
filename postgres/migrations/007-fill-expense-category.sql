BEGIN;

-- ---------------------------------------------------------------------------
--  รายการที่ย้าย และมาตราที่รองรับ
--
--    40(1) 40(2) เงินเดือนและค่าจ้าง        ม.42 ทวิ  หักร้อยละ 50 ไม่เกิน 100,000
--    40(3) ค่าลิขสิทธิ์และกู๊ดวิลล์            ม.42 ตรี  หักร้อยละ 50 ไม่เกิน 100,000
--    40(5) ค่าเช่าทรัพย์สิน                  ม.43      หักตามชนิดทรัพย์สิน 10 ถึง 30
--    40(6) วิชาชีพอิสระ                     ม.44      หักร้อยละ 30 หรือ 60
--    40(7) การรับเหมา                       ม.45      หักร้อยละ 60
--    40(8) ธุรกิจและการพาณิชย์               ม.46      หักร้อยละ 60 ตาม พ.ร.ฎ. ฉบับที่ 11
--
--  รายการที่ตั้งใจไม่ย้าย
--    "เงินได้พึงประเมิน 8 ประเภทตามมาตรา 40" เป็นภาพรวมการจัดประเภทล้วน ๆ
--      ไม่ได้บอกอัตราหัก จึงอยู่หมวดประเภทเงินได้พึงประเมินต่อไป
--    "ดอกเบี้ยและเงินปันผล 40(4)" เงินได้ประเภทนี้หักค่าใช้จ่ายไม่ได้ตามกฎหมาย
-- ---------------------------------------------------------------------------
UPDATE tax_law_knowledge
SET category = 'การหักค่าใช้จ่าย'
WHERE title IN (
  'การหักค่าใช้จ่ายเงินเดือนและค่าจ้าง 40(1) และ 40(2)',
  'การหักค่าใช้จ่ายค่าลิขสิทธิ์และกู๊ดวิลล์ 40(3)',
  'ค่าเช่าทรัพย์สิน 40(5) อัตราหักค่าใช้จ่ายตามประเภททรัพย์สิน',
  'ค่าเช่าทรัพย์สินตามมาตรา 40(5) อัตราหักค่าใช้จ่ายแยกตามชนิดทรัพย์สิน',
  'ฟรีแลนซ์และงานรับจ้าง เข้าประเภทไหน หักค่าใช้จ่ายเท่าไร',
  'วิชาชีพอิสระ 40(6) และการรับเหมา 40(7)',
  'เงินได้จากธุรกิจและการพาณิชย์ 40(8)'
);


-- ---------------------------------------------------------------------------
--  ทุกรายการในหมวดนี้เป็นอัตราที่ต้องเอาไปคิดกับรายได้ของผู้ใช้เสมอ
--
--  ไม่มีรายการไหนในหมวดนี้ที่ตอบได้เลยโดยไม่ต้องคำนวณ
--  เพราะสาระของหมวดนี้คืออัตราและเพดาน ไม่ใช่กำหนดเวลาหรือขั้นตอน
--  จึงตั้งค่าได้ทั้งหมวดโดยไม่ต้องไล่ดูทีละรายการ
--
--  แต่ยังคง calc_verified เป็น false ไว้ตามเดิม
--  เพราะผู้ดูแลควรได้อ่านเนื้อหาจริงก่อนยืนยัน ไม่ใช่เชื่อคำสั่งนี้
-- ---------------------------------------------------------------------------
UPDATE tax_law_knowledge
SET needs_calculation = true
WHERE category = 'การหักค่าใช้จ่าย';

COMMIT;


-- ============================================================================
--  ตรวจผลหลังรัน
-- ============================================================================

-- ต้องได้ 7 แถว ทุกแถว needs_calculation เป็น t
SELECT id, title, needs_calculation, calc_verified
FROM tax_law_knowledge
WHERE category = 'การหักค่าใช้จ่าย'
ORDER BY id;

-- จำนวนรวมของทุกหมวด ต้องยังเท่ากับ 97
SELECT category AS หมวด,
       count(*) AS จำนวน,
       count(*) FILTER (WHERE needs_calculation) AS ต้องคำนวณต่อ
FROM tax_law_knowledge
GROUP BY 1
ORDER BY 2 DESC;


