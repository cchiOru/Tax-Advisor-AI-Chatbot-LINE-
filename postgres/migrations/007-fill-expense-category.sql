--    ตามประมวลรัษฎากร มาตรา 42 ทวิ ถึงมาตรา 46
--    และระบบก็ตอบคำถามเรื่องนี้ได้อยู่แล้ว เช่น หักเหมาร้อยละ 60 ของ 40(8)
--
--    สาเหตุคือรายการเหล่านั้นถูกเขียนรวมกับการจัดประเภทเงินได้มาตั้งแต่แรก
--    จึงถูกจัดอยู่ในหมวดประเภทเงินได้พึงประเมินทั้งหมด
--    ซึ่งไม่ใช่ความผิดพลาด เพราะในทางปฏิบัติสองเรื่องนี้แยกจากกันไม่ได้
--    อัตราหักค่าใช้จ่ายขึ้นกับว่าเงินได้นั้นเป็นประเภทไหน
--
--  ทำไมการย้ายหมวดจึงต้องวัดผลก่อน ไม่ใช่ย้ายได้เลย
--
--    ชื่อหมวดมีน้ำหนักในการค้นหา คูณ 3 รองจากชื่อเรื่องที่คูณ 5
--    การย้ายรายการเข้าหมวดที่ชื่อมีคำว่า "ค่าใช้จ่าย"
--    ทำให้รายการนั้นได้คะแนนเพิ่มทันทีในทุกคำถามที่มีคำว่าค่าใช้จ่าย
--    ซึ่งอาจไปเบียดรายการที่มีคำตอบจริงตกจากอันดับ
--
--  ผลการทดลองก่อนตัดสินใจ ทดสอบกับคำถามชุดทางการ 115 ข้อ
--
--    ย้าย 2 รายการที่ขึ้นต้นว่าการหักค่าใช้จ่าย   ผลค้นเปลี่ยน 5 ข้อ
--    ย้าย 5 รายการที่พูดถึงอัตราหักโดยตรง         ผลค้นเปลี่ยน 4 ข้อ
--    ย้าย 7 รายการที่มีอัตราหักค่าใช้จ่ายทั้งหมด   ผลค้นเปลี่ยน 1 ข้อ  <-- เลือกแบบนี้
--
--    ผลที่ดูขัดความรู้สึกคือ ยิ่งย้ายมาก ผลกระทบยิ่งน้อย
--    เหตุผลคือถ้าย้ายบางส่วน รายการที่ย้ายจะได้เปรียบรายการที่ไม่ได้ย้าย
--    ทั้งที่ทั้งคู่ตอบคำถามแนวเดียวกัน อันดับจึงสลับกันมั่ว
--    เมื่อย้ายทั้งกลุ่ม ทุกรายการได้คะแนนหมวดเท่ากัน ลำดับเดิมจึงคงอยู่
