--    ตัวอย่างความเสียหายของการย้ายไม่ครบ
--      Q85 รับเหมาก่อสร้างหักค่าใช้จ่ายได้กี่เปอร์เซ็นต์
--        ถ้าย้ายแค่ 5 รายการ รายการ "วิชาชีพอิสระ 40(6) และการรับเหมา 40(7)"
--        ซึ่งมีคำตอบร้อยละ 60 อยู่ จะหลุดจากอันดับ
--        แล้วถูกแทนด้วยรายการเงินเดือนกับค่าลิขสิทธิ์ที่ไม่เกี่ยวกับคำถามเลย
--
--  ผลของแบบที่เลือก ย้าย 7 รายการ
--    คำถามที่ผลการค้นเปลี่ยน 1 ข้อ คือ Q29 เงินเดือนหักค่าใช้จ่ายได้เท่าไหร่
--    รายการอันดับหนึ่งยังเป็นรายการเดิมที่มีคำตอบ เปลี่ยนแค่อันดับ 2 และ 3
--    ตรวจแล้วว่าคำที่ใช้ตัดสินคำตอบคือ 50 และ 100,000 ยังอยู่ในบริบททั้งก่อนและหลัง
--    คำถามที่ค้นไม่เจอเลย ยังเป็นศูนย์ทั้งก่อนและหลัง
--
--  ยังต้องวัดผลจริงอีกรอบ
--    การวัดข้างต้นวัดแค่ว่าค้นเจออะไร ไม่ได้วัดว่าตอบถูกไหม
--    ชื่อหมวดถูกส่งเข้าไปในข้อมูลที่ให้ AI อ่านด้วย ถ้อยคำคำตอบจึงอาจเปลี่ยน
--    ต้องรัน evaluation/run-accuracy-test.js --runs=3 หลังรันไฟล์นี้
