      'ถูกกรมสรรพากรเรียกตรวจสอบ ต้องทำอย่างไร',
      'ภาษีมูลค่าเพิ่ม VAT อัตราและเกณฑ์จดทะเบียน',
      'ภาษีธุรกิจเฉพาะและการขายอสังหาริมทรัพย์',
      'ภาษีเงินได้นิติบุคคลและสิทธิประโยชน์ของ SME',
      'ภาษีที่ดินและสิ่งปลูกสร้าง',
      'ภาษีการรับมรดกและภาษีการรับให้'
    ) THEN false

    -- migration 007 ตั้งทั้งหมวดเป็นใช่
    WHEN category = 'การหักค่าใช้จ่าย' THEN true

    -- ที่เหลือใช้เกณฑ์เดาของ migration 006
    ELSE (
      category IN ('การหักลดหย่อน', 'การคำนวณภาษี', 'การหักค่าใช้จ่าย',
                   'ประเภทเงินได้พึงประเมิน', 'เบี้ยปรับ เงินเพิ่ม และโทษ')
      AND (content ~ '[0-9],[0-9]{3}\s*บาท' OR content ~ 'ร้อยละ\s*[0-9]' OR content ~ '[0-9]+%')
