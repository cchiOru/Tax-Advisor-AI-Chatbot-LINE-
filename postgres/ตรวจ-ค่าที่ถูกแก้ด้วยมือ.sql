      'ภาษีที่ดินและสิ่งปลูกสร้าง',
      'ภาษีการรับมรดกและภาษีการรับให้'
    )
  ) AS ระบบยืนยันให้เอง
FROM tax_law_knowledge;


-- ---------------------------------------------------------------------------
--  1) รายการที่ค่าถูกสลับไปจากที่ระบบตั้งไว้ คือถูกกดปุ่มต้องคำนวณต่อ
-- ---------------------------------------------------------------------------
\echo ''
\echo '=== รายการที่ค่าไม่ตรงกับที่ระบบตั้งไว้ (ถูกกดปุ่มสลับค่า) ==='
SELECT id,
       category AS หมวด,
       left(title, 46) AS หัวข้อ,
       ค่าที่ระบบตั้งไว้ AS เดิม,
       ค่าปัจจุบัน       AS ตอนนี้
FROM ค่าที่ควรเป็น
WHERE ค่าปัจจุบัน IS DISTINCT FROM ค่าที่ระบบตั้งไว้
ORDER BY id;


-- ---------------------------------------------------------------------------
--  2) รายการที่ถูกกดยืนยัน
-- ---------------------------------------------------------------------------
\echo ''
\echo '=== รายการที่ถูกกดปุ่มยืนยัน (นอกเหนือจาก 21 รายการที่ระบบยืนยันให้) ==='
SELECT id,
       category AS หมวด,
       left(title, 46) AS หัวข้อ,
       ค่าปัจจุบัน AS ต้องคำนวณต่อ,
       CASE WHEN ค่าปัจจุบัน IS DISTINCT FROM ค่าที่ระบบตั้งไว้
            THEN 'สลับค่าด้วย' ELSE 'ยืนยันค่าเดิม' END AS การกระทำ
FROM ค่าที่ควรเป็น
WHERE ยืนยันแล้ว AND NOT ระบบยืนยันให้เอง
ORDER BY id;


-- ---------------------------------------------------------------------------
--  3) สรุป
-- ---------------------------------------------------------------------------
\echo ''
\echo '=== สรุป ==='
SELECT
  count(*) AS รายการทั้งหมด,
  count(*) FILTER (WHERE ค่าปัจจุบัน IS DISTINCT FROM ค่าที่ระบบตั้งไว้) AS ค่าถูกสลับ,
  count(*) FILTER (WHERE ยืนยันแล้ว AND NOT ระบบยืนยันให้เอง) AS ถูกกดยืนยันเอง,
  count(*) FILTER (WHERE ยืนยันแล้ว) AS ยืนยันแล้วทั้งหมด,
  count(*) FILTER (WHERE NOT ยืนยันแล้ว) AS ยังไม่ยืนยัน
FROM ค่าที่ควรเป็น;


