//  เหลือเผื่อเพียง 341 โทเคนจาก 8,192 ที่ตั้งไว้ใน Modelfile
//
//  อันตรายของเรื่องนี้อยู่ที่ "ไม่มีสัญญาณเตือน" Ollama ตัดข้อมูลส่วนหน้าทิ้ง
//  เงียบ ๆ ซึ่งคือคำสั่งระบบและตัวบทกฎหมาย แล้วยังตอบกลับมาเป็นข้อความปกติ
//  ถ้าไม่ได้คำนวณไว้ก่อน จะเสียเวลารันเกือบชั่วโมงครึ่งเพื่อได้ตัวเลขที่ใช้ไม่ได้
//  และที่แย่กว่านั้นคืออาจเผลอเอาตัวเลขนั้นไปเขียนในรายงาน
