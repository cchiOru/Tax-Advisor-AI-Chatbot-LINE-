//    ไฟล์ seed พังอยู่ฝ่ายเดียว ใครติดตั้งใหม่จากไฟล์จะได้ระบบที่แย่กว่า
//    โดยไม่มีอะไรฟ้อง เพราะไฟล์ยังนำเข้าได้ปกติ
