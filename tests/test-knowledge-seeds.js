'use strict';
/**
 * ============================================================================
 *  ตรวจไฟล์ฐานความรู้ก่อนนำเข้าฐานข้อมูล
 * ----------------------------------------------------------------------------
 *  ที่มาของชุดทดสอบนี้
 *    ตอนนำเข้าฐานความรู้ชุดที่ 8 psql ขึ้นข้อผิดพลาด
 *      ERROR: value too long for type character varying(200)
 *    เพราะช่อง source ของตาราง tax_law_knowledge เป็น VARCHAR(200)
 *    แต่ข้อความอ้างอิงกฎหมายที่เขียนไว้ยาว 289 ตัวอักษร
 *
 *    สิ่งที่ทำให้เรื่องนี้อันตรายกว่าที่เห็น
 *      psql รันคำสั่ง DELETE ผ่านไปแล้วก่อนจะมาพังตอน INSERT
 *      ผลคือถ้าเคยนำเข้าชุดนี้สำเร็จมาก่อน ข้อมูลเดิมจะถูกลบทิ้ง
 *      แล้วข้อมูลใหม่ใส่ไม่เข้า กลายเป็นฐานความรู้หายไปทั้งชุดโดยไม่รู้ตัว
 *      รอบนี้รอดเพราะเป็นการนำเข้าครั้งแรก DELETE จึงลบ 0 แถว
 *
 *    ตรวจย้อนหลังพบว่าไฟล์เดิมเฉียดเพดานอยู่แล้ว
 *      seed-tax-law-deductions-detail.sql  ยาวสุด 184 ตัวอักษร
 *      seed-tax-law-exempt-and-freelance.sql ยาวสุด 160 ตัวอักษร
 *    แปลว่าไม่ใช่ความบังเอิญของชุดที่ 8 อย่างเดียว
 *    แต่เป็นกับดักที่รออยู่ทุกครั้งที่เขียนรายการใหม่พร้อมอ้างอิงกฎหมายยาว ๆ
 *
 *  ชุดทดสอบนี้อ่านไฟล์ .sql โดยตรง จึงจับได้ตั้งแต่ก่อนเอาไปรันกับฐานข้อมูลจริง
 *
 *  วิธีรัน
 *    node --test tests/test-knowledge-seeds.js
 * ============================================================================
 */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const PG_DIR = path.join(__dirname, '..', 'postgres');

/** ความยาวสูงสุดของแต่ละช่อง ตามที่ประกาศไว้ใน CREATE TABLE */
const ความยาวสูงสุด = {
  category: 100,
  source: 200,
};

/** ระยะปลอดภัย ถ้าเข้าใกล้เพดานกว่านี้ให้เตือนไว้ก่อน */
const เหลือน้อยกว่านี้ถือว่าเสี่ยง = 20;

function ไฟล์ฐานความรู้ทั้งหมด() {
  return fs
    .readdirSync(PG_DIR)
    .filter((f) => /^seed-tax-(law|forms).*\.sql$/.test(f))
    .sort();
}

/**
 * ดึงค่าที่จะถูกใส่ลงช่อง source ออกมาจากไฟล์ SQL
 *
 * รายการทุกชุดใช้ธรรมเนียมเดียวกันคือปิดท้าย source ด้วย [ชุดที่ N]
 * จึงใช้เครื่องหมายนี้ระบุตำแหน่งได้แม่นกว่าการไล่นับวงเล็บ
 */
function ดึงข้อความอ้างอิง(sql) {
  const out = [];
  const re = /'((?:[^']|'')*\[ชุดที่ \d+\](?:[^']|'')*)'/g;
  let m;
  while ((m = re.exec(sql)) !== null) {
    const ค่า = m[1].replace(/''/g, "'");
    // ข้ามคำสั่ง DELETE ที่ใช้ pattern สั้น ๆ ว่า %[ชุดที่ N]%
    if (ค่า.startsWith('%') && ค่า.endsWith('%')) continue;
    out.push(ค่า);
  }
  return out;
}

// ---------------------------------------------------------------------------
//  ข้อจำกัดของฐานข้อมูล
// ---------------------------------------------------------------------------

test('KS-01 ข้อความอ้างอิงกฎหมายทุกรายการต้องไม่เกินความยาวที่ช่อง source รับได้', () => {
  const เกิน = [];
  for (const ไฟล์ of ไฟล์ฐานความรู้ทั้งหมด()) {
    const sql = fs.readFileSync(path.join(PG_DIR, ไฟล์), 'utf8');
    for (const ค่า of ดึงข้อความอ้างอิง(sql)) {
      if (ค่า.length > ความยาวสูงสุด.source) {
        เกิน.push(`${ไฟล์} ยาว ${ค่า.length} ตัวอักษร : ${ค่า.slice(0, 60)}...`);
      }
    }
  }
  assert.deepStrictEqual(
    เกิน,
    [],
    `พบข้อความอ้างอิงที่ยาวเกิน ${ความยาวสูงสุด.source} ตัวอักษร นำเข้าแล้วจะพัง\n  ` +
      เกิน.join('\n  ')
  );
});

test('KS-02 ต้องไม่มีรายการไหนเข้าใกล้เพดานจนเสี่ยง', () => {
  // ข้อนี้ไม่ได้กันบั๊กที่เกิดแล้ว แต่กันบั๊กที่กำลังจะเกิด
  // ถ้ามีรายการเหลือที่ว่างไม่ถึง 20 ตัวอักษร แปลว่าครั้งหน้าที่แก้ข้อความนิดเดียวก็พัง
  const เสี่ยง = [];
  for (const ไฟล์ of ไฟล์ฐานความรู้ทั้งหมด()) {
    const sql = fs.readFileSync(path.join(PG_DIR, ไฟล์), 'utf8');
    for (const ค่า of ดึงข้อความอ้างอิง(sql)) {
      const เหลือ = ความยาวสูงสุด.source - ค่า.length;
      if (เหลือ >= 0 && เหลือ < เหลือน้อยกว่านี้ถือว่าเสี่ยง) {
        เสี่ยง.push(`${ไฟล์} ยาว ${ค่า.length} เหลือที่ว่างแค่ ${เหลือ} ตัวอักษร`);
      }
    }
  }
  assert.deepStrictEqual(เสี่ยง, [], 'มีรายการที่เฉียดเพดาน ควรย่อไว้ก่อน\n  ' + เสี่ยง.join('\n  '));
});

