//  หน้าความพึงพอใจ
// ---------------------------------------------------------------------------
async function หน้าความพึงพอใจ(url) {
  const รวม = await query(`
    SELECT count(*) AS ทั้งหมด,
           count(*) FILTER (WHERE is_helpful) AS พอใจ
    FROM answer_feedback
  `);
  const t = Number(รวม[0]?.ทั้งหมด || 0);
  const p = Number(รวม[0]?.พอใจ || 0);
  const ร้อยละ = t ? Math.round((100 * p) / t) : 0;

  // เรียงได้สามแบบ เพราะสองคำถามนี้ต่างกันและตอบด้วยการเรียงคนละแบบ
  //   หมวดไหนคนถามเยอะที่สุด  เรียงตามจำนวน
  //   หมวดไหนระบบตอบได้แย่ที่สุด  เรียงตามสัดส่วนที่ตอบตรง
  const เรียงได้ = {
    จำนวน: 'count(*)',
    ตอบตรง: 'count(*) FILTER (WHERE is_helpful)::numeric / nullif(count(*), 0)',
    หมวด: "coalesce(category, 'ไม่ระบุ')",
  };
  const เรียง = ตัวเรียง(url, เรียงได้, 'จำนวน');

  // นิพจน์เรียงมาจากตารางที่เขียนไว้ในโค้ดนี้ ไม่ได้มาจากที่ผู้ใช้พิมพ์
  const ตามหมวด = await query(`
    SELECT coalesce(category, 'ไม่ระบุ') AS หมวด,
           count(*) AS ทั้งหมด,
           count(*) FILTER (WHERE is_helpful) AS พอใจ
    FROM answer_feedback
    GROUP BY 1 ORDER BY ${เรียง.sql}
  `);

  // ตรวจสมมติฐานว่าค้นไม่เจอหรือตอบช้าทำให้คนไม่พอใจจริงหรือไม่
  const ปัจจัย = await query(`
    SELECT
      round(avg(knowledge_hits)   FILTER (WHERE is_helpful), 2)      AS ค้นเจอเฉลี่ยเมื่อพอใจ,
      round(avg(knowledge_hits)   FILTER (WHERE NOT is_helpful), 2)  AS ค้นเจอเฉลี่ยเมื่อไม่พอใจ,
      round(avg(response_time_ms) FILTER (WHERE is_helpful))         AS เวลาเฉลี่ยเมื่อพอใจ,
      round(avg(response_time_ms) FILTER (WHERE NOT is_helpful))     AS เวลาเฉลี่ยเมื่อไม่พอใจ
    FROM answer_feedback
  `);
  const f = ปัจจัย[0] || {};

  const ต = { เรียงอยู่: เรียง.คีย์, ทิศ: เรียง.ทิศ };
  const แถวหมวด = ตามหมวด
    .map((r) => {
      const n = Number(r.ทั้งหมด), y = Number(r.พอใจ);
      const pc = n ? Math.round((100 * y) / n) : 0;
      return `<tr><td>${esc(r.หมวด)}</td>
        <td class="เลข">${เลข(n)}</td>
        <td class="เลข">${pc}%</td>
        <td style="width:180px"><div class="แท่ง"><i style="width:${pc}%"></i></div></td></tr>`;
    })
    .join('');

  const กราฟจำนวนตามหมวด = แท่งแนวนอน(
    ตามหมวด.map((r) => ({ ป้าย: r.หมวด, ค่า: Number(r.ทั้งหมด) })),
    'ยังไม่มีผู้ใช้กดให้คะแนน'
  );

  return หน้า({
    title: 'ความพึงพอใจ',
    active: '/feedback',
    body: `
<h1>ความพึงพอใจของผู้ใช้</h1>
<p class="คำอธิบาย">
  มาจากปุ่มที่ผู้ใช้กดหลังได้รับคำตอบใน LINE
  เก็บเฉพาะคะแนนกับหมวดคำถาม ไม่เก็บว่าใครกดและไม่เก็บว่าคำตอบนั้นคืออะไร
</p>

<div class="ตัวเลขชุด">
  <div class="ตัวเลข"><div class="ป้าย">คะแนนที่ได้รับทั้งหมด</div>
    <div class="ค่า">${เลข(t)}</div></div>
  <div class="ตัวเลข"><div class="ป้าย">สัดส่วนที่ตอบตรงคำถาม</div>
    <div class="ค่า">${t ? ร้อยละ + '%' : '-'}</div>
    <div class="ท้าย">${t ? `${เลข(p)} จาก ${เลข(t)} ครั้ง` : 'ยังไม่มีข้อมูล'}</div></div>
</div>

<h2>จำนวนคะแนนที่ได้รับ แยกตามหมวด</h2>
<div class="การ์ด">${กราฟจำนวนตามหมวด}
  <p class="บันทึกท้าย">
    กราฟนี้บอกว่าคนถามหมวดไหนมากที่สุด ไม่ได้บอกว่าหมวดไหนตอบดีที่สุด
    ดูสัดส่วนที่ตอบตรงได้จากตารางข้างล่าง
  </p>
</div>

<h2>แยกตามหมวดคำถาม</h2>
<div class="การ์ด">
  ${
    แถวหมวด
      ? `<table><thead><tr>
         ${หัวเรียงได้(url, 'หมวด', 'หมวด', ต)}
         ${หัวเรียงได้(url, 'จำนวน', 'จำนวนที่ให้คะแนน', { ...ต, ชิดขวา: true })}
         ${หัวเรียงได้(url, 'ตอบตรง', 'ตอบตรง', { ...ต, ชิดขวา: true })}
         <th></th></tr></thead><tbody>${แถวหมวด}</tbody></table>
         <p class="บันทึกท้าย">
           เรียงตามสัดส่วนที่ตอบตรงจากน้อยไปมาก จะเห็นหมวดที่ควรแก้ก่อนอยู่บนสุด
           แต่ต้องดูจำนวนคู่ไปด้วย หมวดที่มีคะแนนแค่สองสามครั้ง สัดส่วนแกว่งง่ายมาก
         </p>`
      : '<div class="ว่าง">ยังไม่มีผู้ใช้กดให้คะแนน</div>'
  }
</div>

<h2>ปัจจัยที่อาจเกี่ยวข้อง</h2>
<div class="การ์ด">
  <table>
    <thead><tr><th></th><th class="เลข">เมื่อผู้ใช้พอใจ</th><th class="เลข">เมื่อไม่พอใจ</th></tr></thead>
    <tbody>
      <tr><td>จำนวนรายการที่ค้นเจอเฉลี่ย</td>
        <td class="เลข">${f['ค้นเจอเฉลี่ยเมื่อพอใจ'] ?? '-'}</td>
        <td class="เลข">${f['ค้นเจอเฉลี่ยเมื่อไม่พอใจ'] ?? '-'}</td></tr>
      <tr><td>เวลาตอบเฉลี่ย</td>
        <td class="เลข">${f['เวลาเฉลี่ยเมื่อพอใจ'] ? (f['เวลาเฉลี่ยเมื่อพอใจ']/1000).toFixed(1)+' วิ' : '-'}</td>
        <td class="เลข">${f['เวลาเฉลี่ยเมื่อไม่พอใจ'] ? (f['เวลาเฉลี่ยเมื่อไม่พอใจ']/1000).toFixed(1)+' วิ' : '-'}</td></tr>
    </tbody>
  </table>
  <p class="บันทึกท้าย">
    ตารางนี้ใช้ตั้งข้อสังเกต ไม่ใช่ข้อสรุป ตัวเลขที่ต่างกันบอกได้แค่ว่ามีความสัมพันธ์
    ไม่ได้บอกว่าอะไรเป็นเหตุของอะไร และเมื่อจำนวนคะแนนยังน้อย ความต่างอาจเกิดจากความบังเอิญ
  </p>
</div>`,
  });
}

