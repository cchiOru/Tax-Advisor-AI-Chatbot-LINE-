function ส่ง(res, html, สถานะ = 200, หัวเพิ่ม = {}) {
  res.writeHead(สถานะ, {
    'Content-Type': 'text/html; charset=utf-8',
    // หน้านี้ไม่ควรถูกฝังในเว็บอื่น และไม่ควรเดาชนิดไฟล์เอง
    'X-Frame-Options': 'DENY',
    'X-Content-Type-Options': 'nosniff',
    'Referrer-Policy': 'no-referrer',
    'Cache-Control': 'no-store',
    ...หัวเพิ่ม,
  });
  res.end(html);
}

function พาไป(res, ที่อยู่, หัวเพิ่ม = {}) {
  res.writeHead(302, { Location: ที่อยู่, 'Cache-Control': 'no-store', ...หัวเพิ่ม });
  res.end();
}

async function อ่านฟอร์ม(req) {
  const ชิ้น = [];
  let ขนาด = 0;
  for await (const c of req) {
    ขนาด += c.length;
    // กันการส่งข้อมูลใหญ่ผิดปกติ เนื้อหาความรู้ที่ยาวที่สุดยังไม่ถึง 5 KB
    if (ขนาด > 256 * 1024) throw new Error('ข้อมูลที่ส่งมาใหญ่เกินไป');
    ชิ้น.push(c);
  }
  const params = new URLSearchParams(Buffer.concat(ชิ้น).toString('utf8'));
  const out = {};
  for (const [k, v] of params) out[k] = v;
  return out;
}

