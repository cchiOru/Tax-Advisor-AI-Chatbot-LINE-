// ---------------------------------------------------------------------------
//  เส้นทาง
// ---------------------------------------------------------------------------
async function จัดการคำขอ(req, res) {
  const url = new URL(req.url, `http://${req.headers.host || 'localhost'}`);
  const path = url.pathname;

  // --- เส้นทางที่เข้าได้โดยไม่ต้องล็อกอิน ---
  if (path === '/login' && req.method === 'GET') {
    return ส่ง(res, หน้าล็อกอิน(null));
  }
  if (path === '/login' && req.method === 'POST') {
    const ฟอร์ม = await อ่านฟอร์ม(req);
    if (!รหัสผ่าน) {
      return ส่ง(res, หน้าล็อกอิน('ยังไม่ได้ตั้ง ADMIN_PASSWORD ในไฟล์ .env'), 500);
    }
    if (!รหัสผ่านถูก(ฟอร์ม.password)) {
      // หน่วงเล็กน้อยเพื่อให้การเดารหัสผ่านซ้ำ ๆ ช้าลง
      await new Promise((r) => setTimeout(r, 600));
      return ส่ง(res, หน้าล็อกอิน('รหัสผ่านไม่ถูกต้อง'), 401);
    }
    const id = สร้างเซสชัน();
    return พาไป(res, '/', {
      'Set-Cookie': `sid=${id}; HttpOnly; SameSite=Strict; Path=/; Max-Age=${อายุเซสชัน / 1000}`,
    });
  }

  // --- ตั้งแต่จุดนี้ไปต้องล็อกอินแล้วเท่านั้น ---
  const sid = อ่านคุกกี้(req, 'sid');
  if (!เซสชันใช้ได้(sid)) return พาไป(res, '/login');

  if (path === '/logout') {
    เซสชัน.delete(sid);
    return พาไป(res, '/login', { 'Set-Cookie': 'sid=; HttpOnly; Path=/; Max-Age=0' });
  }

  if (path === '/' && req.method === 'GET') return ส่ง(res, await หน้าภาพรวม(url));
  if (path === '/feedback' && req.method === 'GET') return ส่ง(res, await หน้าความพึงพอใจ(url));
  if (path === '/gaps' && req.method === 'GET') return ส่ง(res, await หน้าช่องว่าง(url));

  const gap = path.match(/^\/gaps\/(\d+)\/(done|wontfix)$/);
  if (gap && req.method === 'POST') {
    await query(
      `UPDATE knowledge_gaps SET status = $2, resolved_at = now() WHERE id = $1`,
      [Number(gap[1]), gap[2] === 'done' ? 'done' : 'wontfix']
    );
    return พาไป(res, '/gaps');
  }

  // หน้าจัดการฐานข้อมูลอยู่ในไฟล์แยก เพราะมีทั้งฟอร์มและการตรวจก่อนบันทึก
  if (path.startsWith('/knowledge')) {
    return ความรู้.จัดการ({ req, res, url, path, ส่ง, พาไป, อ่านฟอร์ม });
  }

  return ส่ง(res, หน้า({ title: 'ไม่พบหน้า', active: '', body: '<h1>ไม่พบหน้านี้</h1>' }), 404);
}

// ---------------------------------------------------------------------------
//  เปิดบริการ
// ---------------------------------------------------------------------------
const server = http.createServer((req, res) => {
  จัดการคำขอ(req, res).catch((e) => {
    // ไม่ส่งรายละเอียดข้อผิดพลาดออกหน้าเว็บ เพราะอาจมีชื่อตารางหรือโครงสร้างภายในติดไปด้วย
    console.error('[ผิดพลาด]', e);
    ส่ง(
      res,
      หน้า({
        title: 'เกิดข้อผิดพลาด',
        active: '',
        body: '<h1>เกิดข้อผิดพลาด</h1><p class="คำอธิบาย">ดูรายละเอียดได้ที่ log ของบริการ</p>',
      }),
      500
    );
  });
});

async function เปิดบริการ() {
  if (!รหัสผ่าน) {
    console.error('ยังไม่ได้ตั้ง ADMIN_PASSWORD ในไฟล์ .env จะเปิดบริการไม่ได้');
    process.exit(1);
  }
  // ด่านสำคัญ ต้องผ่านก่อนถึงจะยอมเปิดบริการ
  await ตรวจว่าอ่านแชทไม่ได้จริง();
  console.log('ตรวจแล้ว บัญชีฐานข้อมูลของหน้าหลังบ้านอ่านตารางบทสนทนาไม่ได้');
  server.listen(PORT, () => console.log(`หน้าหลังบ้านเปิดที่ http://localhost:${PORT}`));
}

// เปิดบริการเฉพาะเมื่อสั่งรันไฟล์นี้ตรง ๆ
// ถ้าถูก require เข้าไปในชุดทดสอบ ให้แค่ส่งฟังก์ชันสร้างหน้าออกไปเฉย ๆ
// ไม่งั้นการทดสอบจะไปเปิดพอร์ตจริงและพยายามต่อฐานข้อมูลจริง
if (require.main === module) {
  เปิดบริการ().catch((e) => {
    console.error('เปิดบริการไม่สำเร็จ:', e.message);
    process.exit(1);
  });
}

