async function หน้ารายการ(url) {
  const คำค้น = (url.searchParams.get('q') || '').trim();
  const หมวดกรอง = (url.searchParams.get('หมวด') || '').trim();
  const คำนวณกรอง = (url.searchParams.get('คำนวณ') || '').trim();

  // ประกอบเงื่อนไขทีละชิ้น โดยนับพารามิเตอร์เอง
  // ค่าที่ผู้ใช้กรอกไปเป็นพารามิเตอร์เสมอ ไม่มีจุดไหนต่อสตริงเข้าไปในคำสั่ง
  const เงื่อนไข = [];
  const ค่า = [];
  if (คำค้น) {
    ค่า.push(`%${คำค้น}%`);
    เงื่อนไข.push(`(title ILIKE $${ค่า.length} OR content ILIKE $${ค่า.length})`);
  }
  if (หมวดที่มีอยู่.includes(หมวดกรอง)) {
    ค่า.push(หมวดกรอง);
    เงื่อนไข.push(`category = $${ค่า.length}`);
  }
  if (คำนวณกรอง === 'ใช่') เงื่อนไข.push('needs_calculation');
  else if (คำนวณกรอง === 'ไม่') เงื่อนไข.push('NOT needs_calculation');
  else if (คำนวณกรอง === 'ยังไม่ได้ตรวจ') เงื่อนไข.push('NOT calc_verified');

  const ที่กรอง = เงื่อนไข.length ? 'WHERE ' + เงื่อนไข.join(' AND ') : '';

  const เรียงได้ = {
    รหัส: 'id',
    หมวด: 'category',
    หัวข้อ: 'title',
    ความยาว: 'length(content)',
    ปีภาษี: 'tax_year',
    ต้องคำนวณ: 'needs_calculation',
  };
  const เรียง = ตัวเรียง(url, เรียงได้, 'รหัส');

  // นิพจน์เรียงและตัวกรองหมวด ถูกกรองผ่านรายการที่เขียนไว้ในโค้ดนี้ก่อนเสมอ
  // ส่วนคำค้นที่ผู้ใช้พิมพ์ ส่งเป็นพารามิเตอร์ ไม่ได้ต่อเข้าไปในคำสั่ง
  const แถว = await query(
    `SELECT id, category, title, source, tax_year, needs_calculation, calc_verified,
            length(content) AS ความยาว
     FROM tax_law_knowledge
     ${ที่กรอง}
     ORDER BY ${เรียง.sql} LIMIT 300`,
    ค่า
  );

  // กราฟนับจากเงื่อนไขเดียวกับตาราง เพื่อให้ตัวเลขสองที่ตรงกันเสมอ
  // ถ้ากราฟนับทั้งฐานข้อมูลแต่ตารางนับเฉพาะที่กรอง จะอ่านขัดกันจนสับสน
  const จำนวนตามหมวด = await query(
    `SELECT category AS หมวด, count(*)::int AS จำนวน
     FROM tax_law_knowledge ${ที่กรอง}
     GROUP BY 1 ORDER BY 2 DESC`,
    ค่า
  );

  const ต = { เรียงอยู่: เรียง.คีย์, ทิศ: เรียง.ทิศ };

  const ยังไม่ได้ตรวจทั้งหมด = await query(
    'SELECT count(*)::int AS n FROM tax_law_knowledge WHERE NOT calc_verified'
  );
  const จำนวนที่ยังไม่ตรวจ = ยังไม่ได้ตรวจทั้งหมด[0] ? ยังไม่ได้ตรวจทั้งหมด[0].n : 0;

  const เนื้อ = แถว
    .map(
      (r) => `<tr>
      <td class="เลข">${r.id}</td>
      <td><span class="ป้ายเล็ก">${esc(r.category)}</span></td>
      <td><a href="/knowledge/${r.id}">${esc(r.title)}</a></td>
      <td>${
        r.needs_calculation
          ? '<span class="ป้ายเล็ก คำนวณ">ต้องคำนวณ</span>'
          : '<span class="ป้ายเล็ก">ตอบได้เลย</span>'
      }${r.calc_verified ? '' : ' <span title="ระบบเดาไว้ ยังไม่มีใครยืนยัน" style="color:#b45309">?</span>'}</td>
      <td class="เลข">${เลข(r.ความยาว)}${
        r.ความยาว > ความยาวเนื้อหาที่เริ่มเสี่ยง
          ? ' <span style="color:#b45309" title="ยาวจนอาจเบียดรายการอื่น">!</span>'
          : ''
      }</td>
      <td class="เลข">${esc(r.tax_year)}</td>
    </tr>`
    )
    .join('');

  const ตัวเลือกหมวด = ['<option value="">ทุกหมวด</option>']
    .concat(
      หมวดที่มีอยู่.map(
        (c) => `<option value="${esc(c)}"${หมวดกรอง === c ? ' selected' : ''}>${esc(c)}</option>`
      )
    )
    .join('');

  const ตัวเลือกคำนวณ = [
    ['', 'ทั้งที่ต้องคำนวณและไม่ต้อง'],
    ['ใช่', 'เฉพาะที่ต้องคำนวณต่อ'],
    ['ไม่', 'เฉพาะที่ตอบได้เลย'],
    ['ยังไม่ได้ตรวจ', `เฉพาะที่ยังไม่มีใครยืนยัน (${เลข(จำนวนที่ยังไม่ตรวจ)})`],
  ]
    .map(
      ([v, ชื่อ]) =>
        `<option value="${esc(v)}"${คำนวณกรอง === v ? ' selected' : ''}>${esc(ชื่อ)}</option>`
    )
    .join('');

  return หน้า({
    title: 'ฐานข้อมูล',
    active: '/knowledge',
    body: `
<h1>ฐานข้อมูลกฎหมาย</h1>
<p class="คำอธิบาย">
  ข้อมูลที่ระบบใช้ตอบคำถามผู้ใช้ แสดงอยู่ ${เลข(แถว.length)} รายการ
  เครื่องหมาย ! หมายถึงรายการยาวเกิน ${เลข(ความยาวเนื้อหาที่เริ่มเสี่ยง)} ตัวอักษร
  ซึ่งอาจเบียดรายการอื่นตกจากงบข้อมูลที่ส่งให้ AI
  ส่วนเครื่องหมาย ? หมายถึงช่องต้องคำนวณต่อยังเป็นค่าที่ระบบเดาไว้
</p>
${
  จำนวนที่ยังไม่ตรวจ
    ? `<div class="แจ้ง เตือน">ยังมี ${เลข(จำนวนที่ยังไม่ตรวจ)} รายการที่ระบบเดาค่าต้องคำนวณต่อไว้ให้
       และยังไม่มีใครยืนยัน เลือกตัวกรองเฉพาะที่ยังไม่มีใครยืนยัน เพื่อไล่ตรวจทีละรายการ</div>`
    : ''
}

<div class="แถวปุ่ม" style="margin-bottom:14px">
  <a class="ปุ่ม" href="/knowledge/new">เพิ่มความรู้ใหม่</a>
</div>

<form method="get" action="/knowledge" class="การ์ด แถวกรอง">
  <input name="q" value="${esc(คำค้น)}" placeholder="ค้นหาในหัวข้อหรือเนื้อหา">
  <select name="หมวด">${ตัวเลือกหมวด}</select>
  <select name="คำนวณ">${ตัวเลือกคำนวณ}</select>
  <!-- คงการเรียงที่เลือกไว้ เวลากดกรองใหม่ ไม่งั้นตารางจะเด้งกลับไปเรียงตามรหัสทุกครั้ง -->
  <input type="hidden" name="เรียง" value="${esc(เรียง.คีย์)}">
  <input type="hidden" name="ทิศ" value="${esc(เรียง.ทิศ)}">
  <button class="รอง" type="submit">กรอง</button>
  ${
    คำค้น || หมวดกรอง || คำนวณกรอง
      ? '<a class="ปุ่ม รอง" href="/knowledge" style="background:#fff;color:#1f2933;border:1px solid #e3e6ea">ล้าง</a>'
      : ''
  }
</form>

${
  // กราฟมีประโยชน์เมื่อมีของให้เทียบกัน
  // ถ้ากรองแล้วเหลือหมวดเดียวหรือไม่เหลือเลย กราฟไม่ได้บอกอะไรเพิ่มจากตาราง
  // จึงซ่อนไปเลย ดีกว่าโชว์กล่องว่างซ้ำกับกล่องข้างล่าง
  จำนวนตามหมวด.length > 1
    ? `<div class="การ์ด">
  ${แท่งแนวนอน(จำนวนตามหมวด.map((r) => ({ ป้าย: r.หมวด, ค่า: r.จำนวน })))}
  <p class="บันทึกท้าย">
    นับเฉพาะรายการที่ตรงกับตัวกรองด้านบน หมวดที่แท่งสั้นผิดปกติคือหมวดที่ข้อมูลยังบาง
    ถ้ามีคนถามเรื่องนั้นบ่อย ควรเติมก่อน
  </p>
</div>`
    : ''
}

<div class="การ์ด">
  ${
    เนื้อ
      ? `<table><thead><tr>
         ${หัวเรียงได้(url, 'รหัส', 'รหัส', { ...ต, ชิดขวา: true })}
         ${หัวเรียงได้(url, 'หมวด', 'หมวด', ต)}
         ${หัวเรียงได้(url, 'หัวข้อ', 'หัวข้อ', ต)}
         ${หัวเรียงได้(url, 'ต้องคำนวณ', 'ต้องคำนวณต่อ', ต)}
         ${หัวเรียงได้(url, 'ความยาว', 'ความยาว', { ...ต, ชิดขวา: true })}
         ${หัวเรียงได้(url, 'ปีภาษี', 'ปีภาษี', { ...ต, ชิดขวา: true })}
         </tr></thead><tbody>${เนื้อ}</tbody></table>`
      : `<div class="ว่าง">
           ${
             หมวดกรอง
               ? `ยังไม่มีรายการไหนอยู่ในหมวด ${esc(หมวดกรอง)}<br>
                  หมวดนี้มีอยู่จริงตามประมวลรัษฎากร แต่ยังไม่มีใครเพิ่มข้อมูลเข้ามา`
               : 'ไม่พบรายการที่ตรงกับเงื่อนไข'
           }
           <div class="แถวปุ่ม" style="justify-content:center;margin-top:12px">
             <a class="ปุ่ม" href="/knowledge/new">เพิ่มความรู้ใหม่</a>
             <a class="ปุ่ม รอง" href="/knowledge"
                style="background:#fff;color:#1f2933;border:1px solid #e3e6ea">ล้างตัวกรอง</a>
           </div>
         </div>`
  }
</div>
${
  // ไม่มีตารางก็ไม่ต้องบอกวิธีเรียงตาราง
  เนื้อ
    ? `<p class="บันทึกท้าย">
         กดที่หัวคอลัมน์เพื่อเรียง เช่น กดความยาวเพื่อหารายการที่ยาวเกินไปและควรแยกเป็นหลายรายการย่อย
       </p>`
    : ''
}`,
  });
}

// ---------------------------------------------------------------------------
//  ตัวจัดการเส้นทาง
// ---------------------------------------------------------------------------
async function จัดการ({ req, res, url, path, ส่ง, พาไป, อ่านฟอร์ม }) {
  // รายการทั้งหมด
  if (path === '/knowledge' && req.method === 'GET') {
    return ส่ง(res, await หน้ารายการ(url));
  }

  // ฟอร์มเพิ่มใหม่
  if (path === '/knowledge/new' && req.method === 'GET') {
    // ตั้งต้นเป็นหมวดค่าลดหย่อน เพราะเป็นหมวดที่มีรายการมากที่สุดและถูกเพิ่มบ่อยที่สุด
    return ส่ง(
      res,
      ฟอร์ม({ ค่า: { tax_year: 2567, category: 'การหักลดหย่อน', needs_calculation: '1' } })
    );
  }

  // บันทึกรายการใหม่ หรือกดทดลองค้น
  if (path === '/knowledge/new' && req.method === 'POST') {
    const f = await อ่านฟอร์ม(req);
    const { ผิด, เตือน } = ตรวจฟอร์ม(f);

    if (f.action === 'test') {
      const ผลค้น = f['ทดลอง'] ? await ทดลองค้น(f['ทดลอง'], f) : null;
      return ส่ง(res, ฟอร์ม({ ค่า: f, เตือน, ผลค้น, คำถามทดลอง: f['ทดลอง'] }));
    }
    if (ผิด.length) return ส่ง(res, ฟอร์ม({ ค่า: f, ผิด, เตือน }));

    // calc_verified เป็นจริงเสมอเมื่อบันทึกผ่านฟอร์ม เพราะมีคนเลือกด้วยมือแล้ว
    // ค่าที่เป็นเท็จมีแค่รายการเก่าที่ migration 006 เดาให้ตอนย้ายหมวด
    const แถว = await query(
      `INSERT INTO tax_law_knowledge
         (category, title, content, source, tax_year, needs_calculation, calc_verified)
       VALUES ($1, $2, $3, $4, $5, $6, true) RETURNING id`,
      [
        f.category,
        f.title.trim(),
        f.content.trim(),
        f.source.trim(),
        Number(f.tax_year),
        เป็นจริง(f.needs_calculation),
      ]
    );
    return พาไป(res, `/knowledge/${แถว[0].id}?ok=เพิ่มรายการใหม่เรียบร้อยแล้ว`);
  }

  // ฟอร์มแก้ไข
  const แก้ = path.match(/^\/knowledge\/(\d+)$/);
  if (แก้ && req.method === 'GET') {
    const แถว = await query(
      `SELECT id, category, title, content, source, tax_year,
              needs_calculation, calc_verified
       FROM tax_law_knowledge WHERE id = $1`,
      [Number(แก้[1])]
    );
    if (!แถว.length) return ส่ง(res, หน้า({ title: 'ไม่พบ', active: '', body: '<h1>ไม่พบรายการนี้</h1>' }), 404);
    return ส่ง(res, ฟอร์ม({ ค่า: แถว[0], สำเร็จ: url.searchParams.get('ok') }));
  }

  // บันทึกการแก้ไข ทดลองค้น หรือลบ
  if (แก้ && req.method === 'POST') {
    const id = Number(แก้[1]);
    const f = await อ่านฟอร์ม(req);
    f.id = id;

    if (f.action === 'delete') {
      await query(`DELETE FROM tax_law_knowledge WHERE id = $1`, [id]);
      return พาไป(res, '/knowledge');
    }
    if (f.action === 'test') {
      const ผลค้น = f['ทดลอง'] ? await ทดลองค้น(f['ทดลอง'], f) : null;
      const { เตือน } = ตรวจฟอร์ม(f);
      return ส่ง(res, ฟอร์ม({ ค่า: f, เตือน, ผลค้น, คำถามทดลอง: f['ทดลอง'] }));
    }

    const { ผิด, เตือน } = ตรวจฟอร์ม(f);
    if (ผิด.length) return ส่ง(res, ฟอร์ม({ ค่า: f, ผิด, เตือน }));

    await query(
      `UPDATE tax_law_knowledge
       SET category = $2, title = $3, content = $4, source = $5, tax_year = $6,
           needs_calculation = $7, calc_verified = true
       WHERE id = $1`,
      [
        id,
        f.category,
        f.title.trim(),
        f.content.trim(),
        f.source.trim(),
        Number(f.tax_year),
        เป็นจริง(f.needs_calculation),
      ]
    );
    return พาไป(res, `/knowledge/${id}?ok=บันทึกการแก้ไขเรียบร้อยแล้ว`);
  }

  return ส่ง(res, หน้า({ title: 'ไม่พบหน้า', active: '', body: '<h1>ไม่พบหน้านี้</h1>' }), 404);
}

module.exports = { จัดการ };
