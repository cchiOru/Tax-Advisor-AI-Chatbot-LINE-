function เป็นจริง(v) {
  return v === true || v === '1' || v === 'true';
}

// ---------------------------------------------------------------------------
//  ตรวจข้อมูลก่อนบันทึก
// ---------------------------------------------------------------------------
function ตรวจฟอร์ม(f) {
  const ผิด = [];
  const เตือน = [];

  if (!f.title || !f.title.trim()) ผิด.push('ต้องกรอกหัวข้อ');
  if (!f.content || !f.content.trim()) ผิด.push('ต้องกรอกเนื้อหา');

  // บังคับกรอกแหล่งอ้างอิง เพราะระบบนี้ตั้งใจให้ผู้ใช้ตรวจสอบย้อนกลับได้เสมอ
  // ความรู้ที่ไม่มีที่มา ใช้ตอบเรื่องเงินของคนอื่นไม่ได้
  if (!f.source || !f.source.trim()) ผิด.push('ต้องกรอกแหล่งอ้างอิงทางกฎหมาย');
  else if (f.source.length > ความยาวสูงสุดของแหล่งอ้างอิง) {
    ผิด.push(
      `แหล่งอ้างอิงยาว ${f.source.length} ตัวอักษร เกินที่ฐานข้อมูลรับได้ ` +
        `${ความยาวสูงสุดของแหล่งอ้างอิง} ตัวอักษร`
    );
  } else if (ความยาวสูงสุดของแหล่งอ้างอิง - f.source.length < 20) {
    เตือน.push('แหล่งอ้างอิงเกือบเต็มความยาวที่รับได้ ครั้งหน้าที่แก้เพิ่มอาจบันทึกไม่ได้');
  }

  if (f.content && f.content.length > ความยาวเนื้อหาที่เริ่มเสี่ยง) {
    เตือน.push(
      `เนื้อหายาว ${เลข(f.content.length)} ตัวอักษร ซึ่งเกิน ${เลข(ความยาวเนื้อหาที่เริ่มเสี่ยง)} ` +
        'รายการยาวมีโอกาสเบียดรายการอื่นตกจากงบข้อมูลที่ส่งให้ AI ' +
        'ควรแยกเป็นหลายรายการย่อยแทน แล้วกดทดลองค้นดูก่อนบันทึก'
    );
  }

  const ปี = Number(f.tax_year);
  if (!ปี || ปี < 2500 || ปี > 2600) ผิด.push('ปีภาษีต้องเป็นปี พ.ศ. เช่น 2567');

  return { ผิด, เตือน };
}

// ---------------------------------------------------------------------------
//  ส่วนแสดงผล
// ---------------------------------------------------------------------------
function กล่องแจ้ง(ผิด, เตือน, สำเร็จ) {
  let out = '';
  if (สำเร็จ) out += `<div class="แจ้ง ดี">${esc(สำเร็จ)}</div>`;
  if (ผิด && ผิด.length) {
    out += `<div class="แจ้ง ผิด"><strong>บันทึกไม่ได้</strong><br>${ผิด.map(esc).join('<br>')}</div>`;
  }
  if (เตือน && เตือน.length) {
    out += `<div class="แจ้ง เตือน"><strong>ข้อควรระวัง</strong><br>${เตือน.map(esc).join('<br>')}</div>`;
  }
  return out;
}

function ผลทดลองค้น(ผล) {
  if (!ผล) return '';
  const รายการ = ผล.รายการ
    .map(
      (r, i) => `<tr>
        <td class="เลข">${i + 1}</td>
        <td>${r.นี่คือรายการใหม่ ? '<span class="ป้ายเล็ก">รายการนี้</span> ' : ''}${esc(r.หัวข้อ)}</td>
        <td class="เลข">${เลข(r.คะแนน)}</td>
        <td class="เลข">${เลข(r.ความยาว)}</td>
        <td>${r.ได้เข้าบริบท ? 'เข้า' : '<span style="color:#b45309">ถูกตัด</span>'}</td>
      </tr>`
    )
    .join('');

  const ติดอันดับ = ผล.รายการ.some((r) => r.นี่คือรายการใหม่ && r.ได้เข้าบริบท);
  const เบียดใครตก = ผล.รายการ.filter((r) => !r.นี่คือรายการใหม่ && !r.ได้เข้าบริบท);

  let สรุป;
  if (ติดอันดับ && !เบียดใครตก.length) {
    สรุป = `<div class="แจ้ง ดี">รายการนี้ถูกค้นเจอและได้เข้าบริบท โดยไม่เบียดรายการเดิมตกไป</div>`;
  } else if (ติดอันดับ) {
    สรุป =
      `<div class="แจ้ง เตือน">รายการนี้ได้เข้าบริบท แต่ทำให้รายการเดิม ` +
      `${เบียดใครตก.length} รายการถูกตัดออก ` +
      `ถ้ารายการที่ถูกตัดมีคำตอบที่ผู้ใช้ต้องการ ระบบจะตอบแย่ลง ` +
      `ลองย่อเนื้อหาให้สั้นลงแล้วทดลองค้นใหม่</div>`;
  } else {
    สรุป =
      `<div class="แจ้ง เตือน">คำถามนี้ค้นไม่เจอรายการนี้ ` +
      `ถ้าตั้งใจให้ตอบคำถามแนวนี้ได้ ควรเพิ่มคำที่ผู้ใช้น่าจะพิมพ์ลงในหัวข้อหรือเนื้อหา</div>`;
  }

  return `<h2>ผลการทดลองค้น</h2>${สรุป}
  <div class="การ์ด">
    <table><thead><tr><th class="เลข">อันดับ</th><th>หัวข้อ</th>
      <th class="เลข">คะแนน</th><th class="เลข">ความยาว</th><th>ผล</th></tr></thead>
      <tbody>${รายการ || '<tr><td colspan="5" class="ว่าง">ค้นไม่เจออะไรเลย</td></tr>'}</tbody></table>
    <p class="บันทึกท้าย">
      งบข้อมูลที่ส่งให้ AI ตั้งไว้ที่ ${เลข(ผล.งบ)} ตัวอักษร
      ระบบจะไล่ตามอันดับแล้วหยิบเฉพาะรายการที่ยังใส่ลงในงบได้
    </p>
  </div>`;
}

