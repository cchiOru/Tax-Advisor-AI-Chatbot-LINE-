const { esc, เลข } = require('./layout');

/**
 * กราฟแท่งแนวตั้ง สำหรับข้อมูลที่เรียงตามเวลา
 *
 * @param {Array<{ป้าย:string, ค่า:number, ป้ายเต็ม?:string}>} ข้อมูล เรียงจากเก่าไปใหม่
 * @param {string} หน่วย        ต่อท้ายตัวเลขในข้อความช่วย เช่น คำถาม
 * @param {string} คำอธิบายว่าง ข้อความที่แสดงเมื่อไม่มีข้อมูล
 */
function แท่งแนวตั้ง(ข้อมูล, หน่วย = '', คำอธิบายว่าง = 'ยังไม่มีข้อมูลพอจะวาดกราฟ') {
  if (!ข้อมูล || ข้อมูล.length === 0) return `<div class="ว่าง">${esc(คำอธิบายว่าง)}</div>`;

  const สูงสุด = Math.max(...ข้อมูล.map((d) => Number(d.ค่า) || 0), 1);

  // ใช้ระบบพิกัดคงที่แล้วให้ SVG ย่อขยายตามความกว้างจริงของจอ
  // วิธีนี้ทำให้กราฟอ่านได้ทั้งบนจอคอมและบนมือถือ โดยไม่ต้องคำนวณซ้ำฝั่งเบราว์เซอร์
  const กว้าง = 1000;
  const สูง = 220;
  const ขอบล่าง = 26; // เว้นที่ให้ป้ายแกนนอน
  const พื้นที่กราฟ = สูง - ขอบล่าง;
  const ช่อง = กว้าง / ข้อมูล.length;
  const กว้างแท่ง = Math.max(2, Math.min(46, ช่อง * 0.62));

  // ถ้าแท่งเยอะจนป้ายทับกัน ให้แสดงป้ายเว้นระยะ แทนที่จะแสดงทุกแท่งจนอ่านไม่ออก
  const เว้นระยะป้าย = Math.ceil(ข้อมูล.length / 14);

  const แท่ง = ข้อมูล
    .map((d, i) => {
      const ค่า = Number(d.ค่า) || 0;
      const h = ค่า === 0 ? 1 : Math.max(2, (ค่า / สูงสุด) * (พื้นที่กราฟ - 6));
      const x = i * ช่อง + (ช่อง - กว้างแท่ง) / 2;
      const y = พื้นที่กราฟ - h;
      const ช่วย = `${d.ป้ายเต็ม || d.ป้าย} ${เลข(ค่า)} ${หน่วย}`.trim();
      const ป้ายแกน =
        i % เว้นระยะป้าย === 0
          ? `<text x="${(i * ช่อง + ช่อง / 2).toFixed(1)}" y="${สูง - 8}"
               text-anchor="middle" class="ป้ายแกน">${esc(d.ป้าย)}</text>`
          : '';
      return `<g><rect x="${x.toFixed(1)}" y="${y.toFixed(1)}"
          width="${กว้างแท่ง.toFixed(1)}" height="${h.toFixed(1)}" rx="3" class="แท่งกราฟ"
          ><title>${esc(ช่วย)}</title></rect>${ป้ายแกน}</g>`;
    })
    .join('');

  // เส้นอ้างอิงแนวนอนสามเส้น ช่วยกะระดับโดยไม่ต้องเอาเมาส์ไปชี้ทีละแท่ง
  const เส้นอ้างอิง = [0.25, 0.5, 0.75, 1]
    .map((ส่วน) => {
      const y = พื้นที่กราฟ - ส่วน * (พื้นที่กราฟ - 6);
      return `<line x1="0" x2="${กว้าง}" y1="${y.toFixed(1)}" y2="${y.toFixed(1)}" class="เส้นอ้างอิง"/>
        <text x="4" y="${(y - 3).toFixed(1)}" class="ป้ายแกน">${เลข(Math.round(สูงสุด * ส่วน))}</text>`;
    })
    .join('');

  return `<svg class="กราฟแท่ง" viewBox="0 0 ${กว้าง} ${สูง}" preserveAspectRatio="none"
    role="img" aria-label="กราฟแท่งแสดง${esc(หน่วย)}">
    ${เส้นอ้างอิง}${แท่ง}
  </svg>`;
}

/**
 * กราฟแท่งแนวนอน สำหรับเปรียบเทียบหมวดหรือกลุ่ม
 * เหมาะกับกรณีที่ชื่อกลุ่มยาว เพราะเขียนชื่อไว้ข้างซ้ายได้เต็มไม่ต้องเอียง
 *
 * @param {Array<{ป้าย:string, ค่า:number, ท้าย?:string}>} ข้อมูล
 */
function แท่งแนวนอน(ข้อมูล, คำอธิบายว่าง = 'ยังไม่มีข้อมูล') {
  if (!ข้อมูล || ข้อมูล.length === 0) return `<div class="ว่าง">${esc(คำอธิบายว่าง)}</div>`;
  const สูงสุด = Math.max(...ข้อมูล.map((d) => Number(d.ค่า) || 0), 1);
  return `<div class="กราฟ">${ข้อมูล
    .map((d) => {
      const ค่า = Number(d.ค่า) || 0;
      const กว้าง = Math.max(ค่า > 0 ? 2 : 0, (ค่า / สูงสุด) * 100);
      return `<span class="ชื่อแกน" title="${esc(d.ป้าย)}">${esc(d.ป้าย)}</span>
        <span class="แท่ง"><i style="width:${กว้าง.toFixed(1)}%"></i></span>
        <span class="ค่าท้าย">${esc(d.ท้าย !== undefined ? d.ท้าย : เลข(ค่า))}</span>`;
    })
    .join('')}</div>`;
}

/**
 * สร้างหัวตารางที่กดเรียงได้
 *
 * รับเฉพาะชื่อคอลัมน์ที่อยู่ในรายการที่กำหนดไว้ในโค้ดเท่านั้น
 * เพราะชื่อคอลัมน์จะถูกนำไปต่อในคำสั่ง ORDER BY ซึ่งใส่เป็นพารามิเตอร์ไม่ได้
 *
 * @param {URL} url          ที่อยู่ปัจจุบัน ใช้คงตัวกรองอื่นไว้เวลากดเรียง
 * @param {string} คีย์      ชื่อที่ใช้ในลิงก์ ต้องตรงกับรายการที่ฝั่งเรียกอนุญาตไว้
 * @param {string} ชื่อ      ข้อความที่แสดง
 * @param {object} ตัวเลือก  { ชิดขวา, เรียงอยู่, ทิศ }
 */
function หัวเรียงได้(url, คีย์, ชื่อ, { ชิดขวา = false, เรียงอยู่, ทิศ } = {}) {
  const กำลังเรียง = เรียงอยู่ === คีย์;
  // กดคอลัมน์เดิมซ้ำคือสลับทิศ กดคอลัมน์ใหม่เริ่มจากมากไปน้อยเสมอ
  // เพราะคนเปิดหน้านี้มักอยากเห็นค่าสูงสุดก่อน
  const ทิศถัดไป = กำลังเรียง && ทิศ === 'มากไปน้อย' ? 'น้อยไปมาก' : 'มากไปน้อย';
  const ที่อยู่ = new URL(url.href);
  ที่อยู่.searchParams.set('เรียง', คีย์);
  ที่อยู่.searchParams.set('ทิศ', ทิศถัดไป);
  const ลูกศร = กำลังเรียง ? (ทิศ === 'มากไปน้อย' ? ' ▾' : ' ▴') : '';
  return `<th${ชิดขวา ? ' class="เลข"' : ''}>
    <a class="หัวเรียง${กำลังเรียง ? ' กำลังเรียง' : ''}"
       href="${esc(ที่อยู่.pathname + ที่อยู่.search)}">${esc(ชื่อ)}${ลูกศร}</a></th>`;
}

/**
 * แปลงค่าเรียงที่รับมาจาก query string ให้เป็นชิ้นส่วน ORDER BY ที่ปลอดภัย
 *
 * @param {URL} url
 * @param {Object<string,string>} ที่อนุญาต  คีย์ในลิงก์ ไปเป็นนิพจน์ SQL ที่เขียนไว้ในโค้ด
 * @param {string} ค่าตั้งต้น
 */
function ตัวเรียง(url, ที่อนุญาต, ค่าตั้งต้น) {
  const ขอ = url.searchParams.get('เรียง') || '';
  const คีย์ = Object.prototype.hasOwnProperty.call(ที่อนุญาต, ขอ) ? ขอ : ค่าตั้งต้น;
  const ทิศ = url.searchParams.get('ทิศ') === 'น้อยไปมาก' ? 'น้อยไปมาก' : 'มากไปน้อย';
  return {
    คีย์,
    ทิศ,
    // ค่าที่คืนไปต่อในคำสั่ง SQL มาจากตารางที่อนุญาตเท่านั้น ไม่ได้มาจากผู้ใช้
    sql: `${ที่อนุญาต[คีย์]} ${ทิศ === 'มากไปน้อย' ? 'DESC' : 'ASC'} NULLS LAST`,
  };
}

module.exports = { แท่งแนวตั้ง, แท่งแนวนอน, หัวเรียงได้, ตัวเรียง };
